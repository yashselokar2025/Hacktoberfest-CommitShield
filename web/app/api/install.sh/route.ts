import { NextResponse } from "next/server";

// Shell installer for Linux/macOS
// The color codes below use single quotes to avoid TS template literal parsing issues
const SCRIPT = [
  "#!/usr/bin/env bash",
  "# SecureVibeCoded installer — Linux / macOS",
  "# Usage: curl -fsSL https://securevibecoded.vercel.app/api/install.sh | bash",
  "",
  "set -e",
  "",
  "RED='\\033[0;31m'",
  "GREEN='\\033[0;32m'",
  "CYAN='\\033[0;36m'",
  "YELLOW='\\033[0;33m'",
  "BOLD='\\033[1m'",
  "NC='\\033[0m'",
  "",
  "echo ''",
  "echo \"${BOLD}${CYAN}🛡  SecureVibeCoded Installer${NC}\"",
  "echo '   Evidence-based, change-aware Git security gate'",
  "echo ''",
  "",
  "# Check Python",
  "if ! command -v python3 &>/dev/null && ! command -v python &>/dev/null; then",
  "  echo \"${RED}✗ Python 3.9+ is required but not found.${NC}\"",
  "  echo '  Install from https://python.org'",
  "  exit 1",
  "fi",
  "",
  "PY=$(command -v python3 || command -v python)",
  "VERSION=$($PY --version 2>&1 | grep -oP '\\d+\\.\\d+' | head -1)",
  "MAJOR=$(echo $VERSION | cut -d. -f1)",
  "MINOR=$(echo $VERSION | cut -d. -f2)",
  "",
  "if [ \"$MAJOR\" -lt 3 ] || { [ \"$MAJOR\" -eq 3 ] && [ \"$MINOR\" -lt 9 ]; }; then",
  "  echo \"${RED}✗ Python 3.9+ required. Found Python $VERSION.${NC}\"",
  "  exit 1",
  "fi",
  "",
  "echo \"  Python $VERSION found ✓\"",
  "",
  "# Check gitleaks",
  "if ! command -v gitleaks &>/dev/null; then",
  "  echo ''",
  "  echo \"${YELLOW}⚠  Gitleaks not found. SecureVibeCoded needs it to scan.${NC}\"",
  "  echo '  Install from: https://github.com/gitleaks/gitleaks/releases'",
  "  echo '  Or: brew install gitleaks (macOS)'",
  "  echo ''",
  "fi",
  "",
  "# Install svc",
  "echo '  Installing securevibecoded...'",
  "$PY -m pip install --quiet git+https://github.com/yashselokar2025/Hacktoberfest-CommitShield.git",
  "",
  "# Verify",
  "if command -v svc &>/dev/null; then",
  "  echo \"${GREEN}✓ Installed: $(svc --version 2>&1)${NC}\"",
  "else",
  "  echo \"${GREEN}✓ Installed (may need to restart shell or add pip bin to PATH)${NC}\"",
  "fi",
  "",
  "echo ''",
  "echo \"${BOLD}Next steps:${NC}\"",
  "echo '  cd your-git-repo'",
  "echo '  svc install      # Add pre-commit hook'",
  "echo '  svc scan         # Manual scan'",
  "echo ''",
  "echo \"${GREEN}Done! Happy coding. 🛡${NC}\"",
].join("\n");

export async function GET() {
  return new NextResponse(SCRIPT, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Content-Disposition": 'attachment; filename="install.sh"',
      "Cache-Control": "public, max-age=3600",
    },
  });
}
